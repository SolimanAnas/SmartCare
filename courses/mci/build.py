#!/usr/bin/env python3
"""
MCI Reviewer build script.

Scans data/mci/** JSON files and emits data/bundle.js which assigns the entire
course dataset to window.MCI_DATA. This lets index.html run by double-clicking
(file://) without a web server, while keeping the per-chapter JSON files as the
canonical, app-integration-friendly source of truth.

Also validates: JSON parse, unique IDs, and chapter cross-references.

Usage:  python build.py
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(ROOT, "data", "mci")
TYPES = ["chapters", "flashcards", "quizzes", "scenarios", "algorithms", "tables", "drills"]
COUNT_KEYS = ("cards", "questions", "cases", "summary", "algorithms", "tables", "drills")
# Practice bank for the shared exam engine (pages/mci.html), generated from the
# reviewer quizzes + scenarios so the two can never drift apart.
PRACTICE_BANK = os.path.join(ROOT, "..", "..", "src", "MCI", "MCI-practice.json")
LETTERS = "ABCDEF"
OPT_PREFIX = re.compile(r"^[A-F][.:)]\s*")


def load(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def write_practice_bank(manifest, dataset):
    """Emit src/MCI/MCI-practice.json in the shared exam-engine shape
    (text / options / correct_answer letter / explanation / hint)."""
    questions = []
    for ch in manifest["chapters"]:
        cid, topic = ch["id"], ch["title"]
        hint = f"Review Chapter {ch['number']}: {topic}."
        for q in dataset["quizzes"].get(cid, {}).get("questions", []):
            questions.append({
                "id": q["id"], "text": q["question"],
                "options": [OPT_PREFIX.sub("", o) for o in q["options"]],
                "correct_answer": LETTERS[q["correct"]], "explanation": q.get("rationale", ""),
                "hint": hint, "difficulty": q.get("difficulty", "").lower(), "topic": topic,
            })
        for c in dataset["scenarios"].get(cid, {}).get("cases", []):
            pearl = f" Pearl: {c['clinicalPearl']}" if c.get("clinicalPearl") else ""
            questions.append({
                "id": c["id"], "text": f"{c['title']} — {c['presentation']} {c['question']}",
                "options": [OPT_PREFIX.sub("", o) for o in c["options"]],
                "correct_answer": LETTERS[c["correct"]],
                "explanation": c.get("explanation", "") + pearl,
                "hint": hint, "difficulty": "scenario", "topic": topic,
            })
    bank = {
        "title": "MCI — Practice Question Bank",
        "description": "AUTO-GENERATED by courses/mci/build.py from the reviewer quizzes and "
                       "scenarios — edit the reviewer JSON, not this file.",
        "questions": questions,
    }
    os.makedirs(os.path.dirname(PRACTICE_BANK), exist_ok=True)
    with open(PRACTICE_BANK, "w", encoding="utf-8") as f:
        json.dump(bank, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"Wrote {os.path.relpath(PRACTICE_BANK, ROOT)} ({len(questions)} questions)")


def main():
    errors, warnings = [], []
    ids = {}

    manifest_path = os.path.join(DATA, "manifest.json")
    if not os.path.exists(manifest_path):
        print("FATAL: manifest.json not found", file=sys.stderr)
        sys.exit(1)
    manifest = load(manifest_path)
    chapter_ids = [c["id"] for c in manifest["chapters"]]

    dataset = {"manifest": manifest}
    for t in TYPES:
        dataset[t] = {}
        for path in sorted(glob.glob(os.path.join(DATA, t, "c*.json"))):
            cid = os.path.splitext(os.path.basename(path))[0]
            try:
                obj = load(path)
            except Exception as e:
                errors.append(f"{t}/{cid}.json: JSON error: {e}")
                continue
            dataset[t][cid] = obj
            # collect IDs for uniqueness check
            for key in COUNT_KEYS[:3] + COUNT_KEYS[4:]:
                for item in obj.get(key, []):
                    iid = item.get("id")
                    if not iid:
                        warnings.append(f"{t}/{cid}.json: item missing id")
                        continue
                    if iid in ids:
                        errors.append(f"Duplicate id '{iid}' in {t}/{cid} and {ids[iid]}")
                    ids[iid] = f"{t}/{cid}"

    # answer-integrity checks
    for cid, obj in dataset["quizzes"].items():
        for q in obj.get("questions", []):
            if not (0 <= q.get("correct", -1) < len(q.get("options", []))):
                errors.append(f"quizzes/{cid}: {q.get('id')} correct index out of range")
    for cid, obj in dataset["scenarios"].items():
        for c in obj.get("cases", []):
            if not (0 <= c.get("correct", -1) < len(c.get("options", []))):
                errors.append(f"scenarios/{cid}: {c.get('id')} correct index out of range")
    for cid, obj in dataset["drills"].items():
        for d in obj.get("drills", []):
            keys = {o["key"] for o in d.get("options", [])}
            for it in d.get("items", []):
                iid = it.get("id")
                if iid in ids:
                    errors.append(f"Duplicate id '{iid}' in drills/{cid} and {ids[iid]}")
                ids[iid] = f"drills/{cid}"
                ans = it.get("answer")
                if "options" in it:
                    if not (isinstance(ans, int) and 0 <= ans < len(it["options"])):
                        errors.append(f"drills/{cid}: {iid} answer index out of range")
                elif ans not in keys:
                    errors.append(f"drills/{cid}: {iid} answer '{ans}' not in drill options")
    for t in TYPES:
        for cid in dataset[t]:
            if cid not in chapter_ids:
                errors.append(f"{t}/{cid}.json: chapter not in manifest")

    # coverage report
    print("=== Coverage ===")
    print(f"{'chap':6}", *[f"{t[:4]:>6}" for t in TYPES])
    for cid in chapter_ids:
        row = []
        for t in TYPES:
            obj = dataset[t].get(cid)
            if obj is None:
                row.append("  -  ")
            else:
                n = 0
                for key in COUNT_KEYS:
                    if isinstance(obj.get(key), list):
                        n = len(obj[key])
                        break
                row.append(f"{n:>5}")
        print(f"{cid:6}", *[f"{c:>6}" for c in row])

    out = os.path.join(ROOT, "data", "bundle.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by build.py — do not edit. Source: data/mci/**\n")
        f.write("window.MCI_DATA = ")
        json.dump(dataset, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")

    print(f"\nWrote {out} ({os.path.getsize(out)//1024} KB)")
    write_practice_bank(manifest, dataset)
    if warnings:
        print(f"\n=== {len(warnings)} warnings ===")
        for w in warnings[:40]:
            print("  WARN:", w)
    if errors:
        print(f"\n=== {len(errors)} ERRORS ===")
        for e in errors:
            print("  ERR:", e)
        sys.exit(2)
    print("\nValidation OK.")


if __name__ == "__main__":
    main()
